def build_crop_summary() -> str:
    counts = _load_dataset_counts()
    report = _load_eval_report()
    per_crop_counts: dict[str, dict[str, int]] = defaultdict(lambda: {"train": 0, "val": 0, "test": 0, "classes": 0})
    crop_metrics: dict[str, list[float]] = defaultdict(list)
    crop_support: dict[str, int] = defaultdict(int)

    for split in ("train", "val", "test"):
        seen: set[str] = set()
        for label, count in counts[split]["per_class"].items():
            crop = _crop_of(label)
            per_crop_counts[crop][split] += int(count)
            if split == "train" and crop not in seen:
                seen.add(crop)
        if split == "train":
            for label in counts["train"]["per_class"]:
                crop = _crop_of(label)
                per_crop_counts[crop]["classes"] += 1

    for label, data in report["per_class_metrics"].items():
        crop = _crop_of(label)
        crop_metrics[crop].append(float(data["f1"]))
        crop_support[crop] += int(data["support"])

    rows = []
    for crop in sorted(per_crop_counts, key=lambda key: per_crop_counts[key]["train"], reverse=True):
        train_count = per_crop_counts[crop]["train"]
        val_count = per_crop_counts[crop]["val"]
        test_count = per_crop_counts[crop]["test"]
        total = train_count + val_count + test_count
        macro_f1 = 100 * sum(crop_metrics[crop]) / max(len(crop_metrics[crop]), 1)
        rows.append(
            f"{_latex_escape(crop)} & "
            f"{per_crop_counts[crop]['classes']} & "
            f"{train_count:,} & "
            f"{val_count:,} & "
            f"{test_count:,} & "
            f"{total:,} & "
            f"{macro_f1:.2f} \\\\"
        )

    body = "\n".join(rows)
    return rf"""
% Auto-generated by tools/reporting/generate_report_tables.py
\begin{{table*}}[!t]
\caption{{Crop-level dataset composition and validation macro F1.}}
\label{{tab:crop_summary}}
\centering
\small
\begin{{tabular}}{{lrrrrrr}}
\toprule
Crop & Classes & Train & Validation & Test & Total & Macro F1 (\%) \\
\midrule
{body}
\bottomrule
\end{{tabular}}
\end{{table*}}
"""


