#!/usr/bin/env python3
"""Generate LaTeX tables for the report from repository artifacts."""

from __future__ import annotations

import csv
import json
import math
import re
from collections import defaultdict
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SECTIONS_DIR = ROOT / "reports" / "tables"
DATASET_COUNTS = ROOT / "reports" / "dataset_counts.json"
EVAL_REPORT = ROOT / "reports" / "evaluation_report.json"
TRAIN_HISTORY = ROOT / "models" / "logs" / "train_history.csv"
APP_FILE = ROOT / "app.py"


def _require(path: Path) -> Path:
    if not path.exists():
        raise SystemExit(f"Required artifact not found: {path}")
    return path


def _latex_escape(value: str) -> str:
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "<": r"\textless{}",
        ">": r"\textgreater{}",
    }
    text = str(value)
    for src, dst in replacements.items():
        text = text.replace(src, dst)
    return text


def _pretty_label(label: str) -> str:
    if "___" in label:
        crop, disease = label.split("___", 1)
        crop = crop.replace("_", " ").replace(",", "")
        disease = disease.replace("_", " ")
        return f"{crop} / {disease}"
    return label.replace("_", " ")


def _write(path: Path, content: str) -> None:
    path.write_text(content.rstrip() + "\n", encoding="utf-8")
    print(f"Wrote {path.relative_to(ROOT)}")


def _load_dataset_counts() -> dict:
    return json.loads(_require(DATASET_COUNTS).read_text(encoding="utf-8"))


def _load_eval_report() -> dict:
    return json.loads(_require(EVAL_REPORT).read_text(encoding="utf-8"))


def _load_train_history() -> list[dict]:
    rows: list[dict] = []
    with _require(TRAIN_HISTORY).open("r", encoding="utf-8", newline="") as handle:
        reader = csv.DictReader(handle)
        for row in reader:
            rows.append(
                {
                    "epoch": int(row["epoch"]),
                    "accuracy": float(row["accuracy"]),
                    "loss": float(row["loss"]),
                    "val_accuracy": float(row["val_accuracy"]),
                    "val_loss": float(row["val_loss"]),
                }
            )
    if not rows:
        raise SystemExit(f"No rows found in training history: {TRAIN_HISTORY}")
    return rows


def _load_class_order() -> list[str]:
    class_indices_path = ROOT / "models" / "class_indices.json"
    class_indices = json.loads(_require(class_indices_path).read_text(encoding="utf-8"))
    return [label for label, _ in sorted(class_indices.items(), key=lambda item: item[1])]


def _crop_of(label: str) -> str:
    if "___" in label:
        return label.split("___", 1)[0].replace(",", "").replace("_", " ")
    return label.replace("_", " ")


def _split_table_rows(rows: list[str], parts: int) -> list[list[str]]:
    chunk_size = math.ceil(len(rows) / parts)
    return [rows[i:i + chunk_size] for i in range(0, len(rows), chunk_size)]


def _parse_routes() -> list[tuple[str, str, str]]:
    text = _require(APP_FILE).read_text(encoding="utf-8")
    route_pattern = re.compile(
        r"@app\.route\('([^']+)'\s*(?:,\s*methods=\[([^\]]+)\])?\)\s*\ndef\s+([A-Za-z_][A-Za-z0-9_]*)",
        re.MULTILINE,
    )
    routes = []
    for path, methods, func_name in route_pattern.findall(text):
        clean_methods = "GET"
        if methods:
            clean_methods = "/".join(part.strip().strip("'") for part in methods.split(","))
        routes.append((path, clean_methods, func_name))
    return routes


