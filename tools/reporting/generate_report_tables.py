def build_crop_metrics_table() -> str:
    report = _load_eval_report()
    per_crop: dict[str, list[float]] = defaultdict(list)
    support_by_crop: dict[str, int] = defaultdict(int)
    for label, data in report["per_class_metrics"].items():
        crop = _crop_of(label)
        per_crop[crop].append(float(data["f1"]))
        support_by_crop[crop] += int(data["support"])

    rows = []
    for crop in sorted(per_crop, key=lambda key: sum(per_crop[key]) / len(per_crop[key])):
        macro_f1 = 100.0 * sum(per_crop[crop]) / len(per_crop[crop])
        rows.append(f"{_latex_escape(crop)} & {len(per_crop[crop])} & {support_by_crop[crop]} & {macro_f1:.2f} \\\\")
    body = "\n".join(rows)
    return rf"""
% Auto-generated by tools/reporting/generate_report_tables.py
\begin{{table}}[!htbp]
\caption{{Validation macro F1 aggregated by crop family.}}
\label{{tab:crop_metrics}}
\centering
\small
\begin{{tabular}}{{lrrr}}
\toprule
Crop & Classes & Support & Macro F1 (\%) \\
\midrule
{body}
\bottomrule
\end{{tabular}}
\end{{table}}
"""


